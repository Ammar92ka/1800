/** مشروع قومي من كتالوج اللعبة. */
data class ProjectDef(
    val key: String,
    val name: String,
    val about: String,
    val fromYear: Int,
    val cost: Double,
    val minHalves: Int,
    val maxHalves: Int,
    val lines: Map<String, Double> = emptyMap(),
    val effects: Effects = Effects(),
    val upkeepLine: String = "admin",
    val upkeep: Double = 0.0,
    val powers: Map<String, Int> = emptyMap(),
    val schools: Double = 0.0,
    val literacy: Double = 0.0,
    val corruption: Double = 0.0,
    val inflation: Double = 0.0,
    val mood: Double = 0.0,
    val provinceMood: Map<String, Double> = emptyMap(),
    val perk: String = "",
) {
    val benefits: String
        get() {
            val parts = mutableListOf<String>()
            val lineNames = mapOf(
                "customs" to "الجمارك",
                "land" to "ضرائب الأرض",
                "provinces" to "إيراد الولايات",
                "other" to "إيرادات أخرى",
            )
            lines.forEach { (k, v) ->
                parts.add("${lineNames[k] ?: k} +${(v * 100).roundToInt()}% من الإيراد")
            }
            val e = effects
            if (e.legitimacy != 0) parts.add("الشرعية ${if (e.legitimacy > 0) "+" else ""}${e.legitimacy}")
            if (e.stability != 0) parts.add("الاستقرار ${if (e.stability > 0) "+" else ""}${e.stability}")
            if (e.army != 0) parts.add("الجيش ${if (e.army > 0) "+" else ""}${e.army}")
            if (e.foreign != 0) parts.add("المكانة ${if (e.foreign > 0) "+" else ""}${e.foreign}")
            if (e.education != 0) parts.add("التعليم ${if (e.education > 0) "+" else ""}${e.education}")
            if (schools > 0) parts.add("مدارس +${schools.roundToInt()}")
            if (corruption < 0) parts.add("فساد أقل")
            if (inflation < 0) parts.add("تضخم أقل")
            if (mood > 0 || provinceMood.isNotEmpty()) parts.add("رضا الولايات أعلى")
            when (perk) {
                "drought" -> parts.add("يخفف خسائر الجفاف")
                "plague" -> parts.add("يخفف خسائر الطاعون")
                "credit" -> parts.add("يرفع التصنيف الائتماني")
                "logistics" -> parts.add("يرفع قوتنا في الحرب")
                "tech" -> parts.add("جيش أحدث في الحرب")
                "granary" -> parts.add("يخفف صدمات أسعار الحبوب")
                "security" -> parts.add("يقلل المؤامرات")
                "defense" -> parts.add("يقوي دفاعنا في الحروب")
                "trade" -> parts.add("يرفع عوائد المعاهدات التجارية")
            }
            return parts.joinToString("، ")
        }

    fun effectiveAbout(s: GameState? = null): String {
        if (key == "modern_army" && s?.powers?.get("janissaries")?.dissolved == true) {
            return "فرق نظامية مدربة على النظام الأوروبي الحديث لسد الفراغ العسكري بعد طي صفحة الانكشارية."
        }
        if (key == "land_registry" && s?.powers?.get("tax_farmers")?.dissolved == true) {
            return "مسح وتسجيل للأراضي يوسع الجباية ويقلل التهرب الضريبي."
        }
        return about
    }
}

